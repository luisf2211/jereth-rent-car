/**
 * Widen the literal `as const` values to `string` so other dictionaries (en)
 * only need to match the SHAPE (same keys/namespaces), not the exact Spanish
 * text. `as const` on `es` still gives us autocomplete + missing-key checks.
 */
type Widen<T> = {
  [K in keyof T]: T[K] extends string ? string : Widen<T[K]>;
};

export type Dictionary = Widen<typeof es>;
